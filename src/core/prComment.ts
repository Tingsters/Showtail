/**
 * The pull-request comment `showtail submit --pr` can post.
 *
 * It is a *summary*, never the report: counts, a timeline, the files touched, a few
 * prompt excerpts, and the fingerprint of the full report (so an instructor who
 * received the report separately can confirm it is the same one). It is built only
 * from data that has already been through the sanitiser, then scanned again.
 *
 * A comment on a public repository is public and permanent (edits stay visible in
 * its history), which is why this is small, why the student sees the exact text
 * first, and why it is only ever posted once and never edited.
 */
import type { ReportData } from '../types.ts';
import {
  approvalCode,
  neutralize,
  scanComment,
} from '@showtail/agent-traces/share/comment';
import type { SubmissionManifest } from './submission.ts';

export { approvalCode, neutralize, scanComment };

/** GitHub rejects bodies over ~65k characters; stay well under. */
const MAX_BODY = 30_000;
const MAX_PROMPTS = 8;
const MAX_PROMPT_CHARS = 140;
const MAX_FILES = 15;

function excerpt(text: string): string {
  const flat = neutralize(text);
  return flat.length > MAX_PROMPT_CHARS
    ? `${flat.slice(0, MAX_PROMPT_CHARS - 1)}…`
    : flat;
}

function span(first: string, last: string): string {
  const ms = Date.parse(last) - Date.parse(first);
  if (!Number.isFinite(ms) || ms < 0) return '';
  const min = Math.round(ms / 60_000);
  if (min < 1) return 'under a minute';
  if (min < 90) return `${min} min`;
  const h = ms / 3_600_000;
  return h < 48 ? `${h.toFixed(1)} hours` : `${Math.round(h / 24)} days`;
}

/** Build the comment body from sanitised report data and the signed manifest. */
export function buildPrComment(data: ReportData, manifest: SubmissionManifest): string {
  const turns = data.turns;
  const first = turns[0]?.prompt.timestamp;
  const last = turns[turns.length - 1]?.prompt.timestamp;
  const files = [...new Set(turns.flatMap((t) => t.codeChanges.map((c) => c.path)))];
  const who = data.scope?.name ?? data.displayName;

  const lines: string[] = [
    '### Showtail work summary',
    '',
    `**${neutralize(who)}**'s prompts to AI tools and the files changed along the way, recorded by [Showtail](https://github.com/Tingsters/Showtail) while building this.`,
    '',
    `- **Exchanges with AI:** ${turns.length}`,
    `- **Files changed:** ${files.length}`,
  ];
  if (first && last) {
    const s = span(first, last);
    lines.push(
      `- **Worked over:** ${first.slice(0, 10)} to ${last.slice(0, 10)}${s ? ` (${s} between first and last prompt)` : ''}`,
    );
  }
  if (data.tools.length > 0) {
    lines.push(
      `- **AI tools:** ${data.tools.map((t) => `${neutralize(String(t.tool))} (${t.events})`).join(', ')}`,
    );
  }
  lines.push(
    `- **Sanitised before sharing:** ${manifest.withheld.total} value(s) withheld (secrets, personal data, opaque tokens)`,
  );

  if (files.length > 0) {
    lines.push('', '<details><summary>Files changed</summary>', '');
    for (const f of files.slice(0, MAX_FILES)) lines.push(`- ${neutralize(f)}`);
    if (files.length > MAX_FILES) lines.push(`- … and ${files.length - MAX_FILES} more`);
    lines.push('', '</details>');
  }
  if (turns.length > 0) {
    lines.push('', '<details><summary>Prompts (excerpts)</summary>', '');
    turns
      .slice(0, MAX_PROMPTS)
      .forEach((t, i) => lines.push(`${i + 1}. ${excerpt(t.prompt.text)}`));
    if (turns.length > MAX_PROMPTS)
      lines.push(`… and ${turns.length - MAX_PROMPTS} more`);
    lines.push('', '</details>');
  }

  lines.push(
    '',
    '**Report fingerprint** (compare with the report handed to your instructor):',
    '',
    `\`sha256:${manifest.files['report.html']}\``,
    '',
    `<sub>report.html, signed with key \`${manifest.keyId}\`. The fingerprint shows the report is unchanged since it was generated; it does not show who generated it. Generated by Showtail ${manifest.version}.</sub>`,
  );

  const body = lines.join('\n');
  return body.length > MAX_BODY
    ? `${body.slice(0, MAX_BODY - 20)}\n\n… (truncated)`
    : body;
}
